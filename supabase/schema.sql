-- Run this entire script in Supabase Dashboard > SQL Editor.
-- Registration records are private. The service-role key is used only by the server.

create table if not exists public.award_registrations (
  id bigint generated by default as identity primary key,
  data jsonb not null,
  created_at timestamptz not null default now()
);

create table if not exists public.award_settings (
  id integer primary key check (id = 1),
  event_at timestamptz,
  updated_at timestamptz not null default now()
);

alter table public.award_registrations enable row level security;
alter table public.award_settings enable row level security;

-- No public or anon policies are created. All reads/writes go through the
-- server using SUPABASE_SERVICE_ROLE_KEY, which must never be exposed in browser code.
